local function check()
  vim.opt.rtp:prepend(vim.env.NVIM_IDE_CONFIG or vim.fn.stdpath('config'))
  vim.cmd('filetype on')
  local project = require('custom.ide.project')
  local base = vim.fn.tempname() .. ' ide project [a]'
  local root, inner = base .. '/repo', base .. '/repo/packages/app'
  vim.fn.mkdir(root .. '/.git', 'p')
  vim.fn.mkdir(inner .. '/src', 'p')
  vim.fn.writefile({'{}'}, root .. '/package.json')
  vim.fn.writefile({'{}'}, inner .. '/package.json')
  local source = inner .. '/src/main.ts'
  vim.fn.writefile({'const answer = 42;'}, source)
  vim.cmd.edit(vim.fn.fnameescape(source))
  assert(project.root() == inner, 'nested package must win over outer repository')
  vim.fn.mkdir(base .. '/other', 'p')
  vim.cmd.cd(vim.fn.fnameescape(base .. '/other'))
  assert(project.root() == inner, 'root must follow file, not unrelated cwd')
  local python = base .. '/python'
  vim.fn.mkdir(python .. '/.venv/bin', 'p')
  vim.fn.mkdir(python .. '/src', 'p')
  vim.fn.writefile({'[project]', 'name = "sample"'}, python .. '/pyproject.toml')
  vim.fn.writefile({'print(42)'}, python .. '/src/main.py')
  vim.fn.writefile({'#!/bin/sh', 'exit 0'}, python .. '/.venv/bin/python')
  vim.fn.setfperm(python .. '/.venv/bin/python', 'rwx------')
  vim.cmd.edit(vim.fn.fnameescape(python .. '/src/main.py'))
  assert(project.python() == python .. '/.venv/bin/python', 'local venv must be used for Python')
  vim.env.VIRTUAL_ENV = base .. '/unrelated-venv'
  assert(project.python() == python .. '/.venv/bin/python', 'project venv must win over inherited unrelated venv')
  vim.env.VIRTUAL_ENV = nil
  local requirements = base .. '/requirements-project'
  vim.fn.mkdir(requirements .. '/src', 'p')
  vim.fn.mkdir(requirements .. '/.venv/bin', 'p')
  vim.fn.writefile({'pytest'}, requirements .. '/requirements.txt')
  vim.fn.writefile({'#!/bin/sh', 'exit 0'}, requirements .. '/.venv/bin/python')
  vim.fn.setfperm(requirements .. '/.venv/bin/python', 'rwx------')
  vim.cmd.edit(vim.fn.fnameescape(requirements .. '/src/main.py'))
  assert(project.python() == requirements .. '/.venv/bin/python', 'requirements project opened outside cwd must use its own venv')
  local plain = base .. '/plain'
  vim.fn.mkdir(plain, 'p')
  vim.cmd.edit(vim.fn.fnameescape(plain .. '/orphan.c'))
  assert(project.root() == plain, 'orphan outside cwd must use its own directory')
  vim.cmd.cd(vim.fn.fnameescape(base))
  assert(project.root() == plain, 'standalone source inside cwd must use its directory, not recursively scan cwd')
  vim.fn.mkdir(base .. '/.git', 'p')
  assert(project.root() == plain, 'empty permission-marker .git directory must not become a project')
  vim.api.nvim_buf_set_lines(0, 0, -1, false, {'unsaved'})
  assert(not project.saved(), 'run/build must reject modified source buffers')
  vim.cmd('edit!')
  assert(project.saved(), 'saved project should be runnable')
  local tasks = require('custom.ide.tasks')
  vim.cmd.edit(vim.fn.fnameescape(python .. '/src/main.py'))
  local plan = tasks.plan('run')
  assert(vim.deep_equal(plan[1].cmd, {python .. '/.venv/bin/python', python .. '/src/main.py'}), 'Python run uses project interpreter and complete path')
  assert(vim.deep_equal(tasks.plan('build')[1].cmd, {python .. '/.venv/bin/python', '-m', 'py_compile', python .. '/src/main.py'}), 'Python build checks the source without scanning environments or the home directory')
  vim.fn.writefile({'#!/bin/bash', 'items=(one two)', 'printf "%s\\n" "${items[1]}"'}, plain .. '/bash.sh')
  vim.cmd.edit(vim.fn.fnameescape(plain .. '/bash.sh'))
  assert(tasks.plan('run')[1].cmd[1] == 'bash', 'bash shebang must not run under dash/sh')
  vim.cmd.edit(vim.fn.fnameescape(plain .. '/orphan.c'))
  vim.bo.filetype = 'c'
  plan = tasks.plan('run')
  local compiler_index = vim.fn.executable('ccache') == 1 and 2 or 1
  assert(#plan == 2 and plan[1].cmd[compiler_index] == 'gcc', 'C run compiles before launching, through ccache when available')
  assert(plan[2].cmd[1] == plan[1].cmd[#plan[1].cmd], 'run launches exactly the compiled executable')
  vim.fn.mkdir(root .. '/rust/src', 'p')
  vim.fn.writefile({'[package]', 'name="sample"', 'version="0.1.0"'}, root .. '/rust/Cargo.toml')
  vim.cmd.edit(vim.fn.fnameescape(root .. '/rust/src/main.rs'))
  vim.bo.filetype = 'rust'
  plan = tasks.plan('test')
  assert(vim.deep_equal(plan[1].cmd, {'cargo', 'test'}) and plan[1].cwd == root .. '/rust', 'Rust tests use the nested Cargo project')
  vim.fn.delete(base, 'rf')
  print('PASS: roots, Python environment, unsaved protection, native compile/run chain, Cargo project tests')
end
local ok, err = xpcall(check, debug.traceback)
if not ok then io.stderr:write(err .. '\n'); vim.cmd('cquit 1') end
vim.cmd('qa!')
